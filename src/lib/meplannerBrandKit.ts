export function resolveThemeWebkitBundle(params: {
  catalogThemeId?: string;
  themePreset?: string;
  layoutArchetype?: string;
  eventType?: string;
}): ThemeWebkitBundle {
  const id = (params.catalogThemeId || '').toLowerCase();
  const preset = (params.themePreset || '').toLowerCase();
  const archetype = (params.layoutArchetype || '').toUpperCase();
  const ev = (params.eventType || '').toUpperCase();

  // 1. Match specific catalogThemeId keywords
  if (
    id.includes('kids') ||
    id.includes('pastel-cloud') ||
    id.includes('wonder') ||
    id.includes('1st')
  ) {
    return ALL_CORNER_CLUSTER_PRESETS[7]; // 8: Kids Pastel Cloud
  }
  if (
    id.includes('blubloom') ||
    id.includes('azure') ||
    id.includes('dusty-rose') ||
    preset === 'blubloom_azure'
  ) {
    return ALL_CORNER_CLUSTER_PRESETS[0]; // 1: BluBloom & Dusty Rose
  }
  if (
    id.includes('kraton') ||
    id.includes('javanese') ||
    id.includes('wayang') ||
    id.includes('sunda') ||
    id.includes('bali') ||
    id.includes('minang') ||
    id.includes('nusantara') ||
    preset === 'javanese_kraton' ||
    preset === 'wayang_gold' ||
    archetype === 'NUSANTARA_HERITAGE'
  ) {
    return ALL_CORNER_CLUSTER_PRESETS[3]; // 4: Javanese Kraton & Ronce
  }
  if (
    id.includes('rustic') ||
    id.includes('pampas') ||
    id.includes('barn') ||
    id.includes('terracotta') ||
    preset === 'espresso_rustic' ||
    preset === 'terracotta_rust'
  ) {
    return ALL_CORNER_CLUSTER_PRESETS[2]; // 3: Rustic Wood & Pampas
  }
  if (
    id.includes('polaroid') ||
    id.includes('photovit') ||
    id.includes('snapshot') ||
    id.includes('magazine') ||
    archetype === 'POLAROID_MAGAZINE'
  ) {
    return ALL_CORNER_CLUSTER_PRESETS[5]; // 6: Polaroid Editorial
  }
  if (
    ev === 'GRADUATION' ||
    id.includes('grad-') ||
    id.includes('cumlaude') ||
    id.includes('academic')
  ) {
    return ALL_CORNER_CLUSTER_PRESETS[6]; // 7: Academic Cum Laude & Gala
  }
  if (
    ev === 'BIRTHDAY' ||
    id.includes('bday-') ||
    id.includes('sweet-17') ||
    id.includes('glamour') ||
    preset === 'blush_rose'
  ) {
    return ALL_CORNER_CLUSTER_PRESETS[4]; // 5: Sweet 17th Blush & Glamour
  }
  if (
    ev === 'MEETING' ||
    ev === 'GALA_DINNER' ||
    id.includes('meet-') ||
    id.includes('gala-') ||
    preset === 'royal_navy' ||
    preset === 'midnight_elegance' ||
    archetype === 'MODERN_BENTO'
  ) {
    return {
      ...ALL_CORNER_CLUSTER_PRESETS[6],
      cardCornerSvg:
        archetype === 'MODERN_BENTO'
          ? MEPLANNER_WEBKIT_COMPONENTS.corner5BentoCyberHud
          : MEPLANNER_WEBKIT_COMPONENTS.corner4RoyalAcademicLaurel,
      themeOrnamentSvg:
        archetype === 'MODERN_BENTO'
          ? MEPLANNER_THEME_ASSETS.ornamentBentoVipPass
          : MEPLANNER_THEME_ASSETS.ornamentRoyalCrest,
    };
  }
  if (
    id.includes('serein') ||
    id.includes('gardenia') ||
    id.includes('botanical') ||
    id.includes('sage') ||
    preset === 'sage_botanical' ||
    archetype === 'BOTANICAL_AIRY'
  ) {
    return ALL_CORNER_CLUSTER_PRESETS[1]; // 2: Gardenia Sage Botanical
  }

  // Default for Wedding Champagne Gold / Editorial Classic
  return {
    ...ALL_CORNER_CLUSTER_PRESETS[0],
    cardCornerSvg: MEPLANNER_WEBKIT_COMPONENTS.corner1NusantaraUkir,
    sectionDividerSvg: MEPLANNER_WEBKIT_COMPONENTS.divider1GununganKraton,
    badgeOrnamentSvg: MEPLANNER_WEBKIT_COMPONENTS.sealWaxRoyalCrimson,
    buttonStyleFamily: 'nusantara',
  };
}
